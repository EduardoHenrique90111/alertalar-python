-- =====================================================================
-- AlertaLar - esquema inicial (PostgreSQL)
-- =====================================================================

-- Fontes de dados utilizadas (APIs, bases geográficas, importações oficiais, relatos)
CREATE TABLE fonte_dados (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(60)   NOT NULL UNIQUE,
    nome               VARCHAR(200)  NOT NULL,
    tipo               VARCHAR(30)   NOT NULL,
    url                VARCHAR(500),
    status_integracao  VARCHAR(30)   NOT NULL,
    oficial            BOOLEAN       NOT NULL DEFAULT FALSE,
    data_atualizacao   TIMESTAMPTZ,
    descricao          VARCHAR(1000),
    atribuicao         VARCHAR(500),
    CONSTRAINT ck_fonte_tipo CHECK (tipo IN ('API_EXTERNA', 'BASE_GEOGRAFICA', 'IMPORTACAO_OFICIAL', 'RELATO_USUARIO')),
    CONSTRAINT ck_fonte_status CHECK (status_integracao IN ('ATIVA', 'IMPORTACAO_MANUAL', 'REQUER_CREDENCIAL', 'PLANEJADA'))
);

-- Usuários (senha sempre armazenada como hash BCrypt)
CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120) NOT NULL,
    email          VARCHAR(254) NOT NULL,
    senha_hash     VARCHAR(100) NOT NULL,
    papel          VARCHAR(20)  NOT NULL DEFAULT 'USUARIO',
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    data_cadastro  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_papel CHECK (papel IN ('USUARIO', 'ADMIN'))
);
CREATE UNIQUE INDEX ux_usuario_email ON usuario (lower(email));

-- Endereços geocodificados (também funciona como cache de geocodificação)
CREATE TABLE endereco (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cep                   VARCHAR(9),
    rua                   VARCHAR(200),
    numero                VARCHAR(20),
    bairro                VARCHAR(120),
    cidade                VARCHAR(120)     NOT NULL,
    estado                VARCHAR(2)       NOT NULL,
    codigo_ibge           VARCHAR(7),
    latitude              DOUBLE PRECISION NOT NULL,
    longitude             DOUBLE PRECISION NOT NULL,
    precisao              VARCHAR(20)      NOT NULL,
    fonte_geocodificacao  VARCHAR(60),
    chave_normalizada     VARCHAR(500),
    data_geocodificacao   TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT ck_endereco_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_endereco_lon CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_endereco_precisao CHECK (precisao IN ('NUMERO', 'RUA', 'MANUAL'))
);
CREATE UNIQUE INDEX ux_endereco_chave ON endereco (chave_normalizada) WHERE chave_normalizada IS NOT NULL;
CREATE INDEX ix_endereco_ibge ON endereco (codigo_ibge);

-- Consultas de risco realizadas
CREATE TABLE consulta (
    id                  UUID PRIMARY KEY,
    endereco_id         BIGINT           NOT NULL REFERENCES endereco (id),
    usuario_id          BIGINT           REFERENCES usuario (id) ON DELETE SET NULL,
    classificacao       VARCHAR(30)      NOT NULL,
    indice              DOUBLE PRECISION,
    justificativa       TEXT             NOT NULL,
    versao_metodologia  VARCHAR(10)      NOT NULL,
    dados_mapa          TEXT,
    data_consulta       TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT ck_consulta_classificacao CHECK (classificacao IN ('BAIXO', 'MODERADO', 'ALTO', 'DADOS_INSUFICIENTES'))
);
CREATE INDEX ix_consulta_usuario ON consulta (usuario_id, data_consulta DESC);

-- Fatores avaliados em cada consulta (justificativa detalhada e rastreável)
CREATE TABLE consulta_fator (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id      UUID             NOT NULL REFERENCES consulta (id) ON DELETE CASCADE,
    ordem            INTEGER          NOT NULL,
    codigo           VARCHAR(40)      NOT NULL,
    nome             VARCHAR(120)     NOT NULL,
    categoria        VARCHAR(30)      NOT NULL,
    situacao         VARCHAR(20)      NOT NULL,
    pontuacao        INTEGER,
    peso             DOUBLE PRECISION NOT NULL,
    valor_observado  VARCHAR(500),
    explicacao       VARCHAR(2000)    NOT NULL,
    fonte_id         BIGINT           REFERENCES fonte_dados (id),
    data_referencia  TIMESTAMPTZ,
    CONSTRAINT ck_fator_categoria CHECK (categoria IN ('RISCO_MAPEADO', 'SUSCETIBILIDADE', 'HISTORICO')),
    CONSTRAINT ck_fator_situacao CHECK (situacao IN ('AVALIADO', 'SEM_REGISTRO', 'INDISPONIVEL')),
    CONSTRAINT ck_fator_pontuacao CHECK (pontuacao IS NULL OR pontuacao BETWEEN 0 AND 3)
);
CREATE INDEX ix_consulta_fator_consulta ON consulta_fator (consulta_id);

-- Ocorrências de enchentes/alagamentos: registros oficiais e relatos de usuários
CREATE TABLE ocorrencia (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endereco_id           BIGINT           REFERENCES endereco (id) ON DELETE SET NULL,
    localizacao           VARCHAR(300)     NOT NULL,
    municipio             VARCHAR(120),
    estado                VARCHAR(2),
    codigo_ibge           VARCHAR(7),
    data_ocorrencia       DATE             NOT NULL,
    descricao             VARCHAR(2000)    NOT NULL,
    tipo_evento           VARCHAR(20)      NOT NULL,
    origem                VARCHAR(20)      NOT NULL,
    status_validacao      VARCHAR(20)      NOT NULL,
    nivel_localizacao     VARCHAR(20)      NOT NULL,
    latitude              DOUBLE PRECISION,
    longitude             DOUBLE PRECISION,
    fonte_id              BIGINT           NOT NULL REFERENCES fonte_dados (id),
    identificador_externo VARCHAR(120),
    nome_relator          VARCHAR(120),
    contato_relator       VARCHAR(254),
    usuario_id            BIGINT           REFERENCES usuario (id) ON DELETE SET NULL,
    validado_por_id       BIGINT           REFERENCES usuario (id) ON DELETE SET NULL,
    data_validacao        TIMESTAMPTZ,
    observacao_validacao  VARCHAR(500),
    data_registro         TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT ck_ocorrencia_tipo CHECK (tipo_evento IN ('ALAGAMENTO', 'INUNDACAO', 'ENXURRADA', 'OUTRO')),
    CONSTRAINT ck_ocorrencia_origem CHECK (origem IN ('OFICIAL', 'RELATO_USUARIO')),
    CONSTRAINT ck_ocorrencia_status CHECK (status_validacao IN ('PENDENTE', 'CONFIRMADA', 'REJEITADA')),
    CONSTRAINT ck_ocorrencia_nivel CHECK (nivel_localizacao IN ('PONTO', 'MUNICIPIO')),
    CONSTRAINT ck_ocorrencia_par_coordenadas CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CONSTRAINT ck_ocorrencia_ponto_tem_coordenadas CHECK (nivel_localizacao <> 'PONTO' OR latitude IS NOT NULL),
    CONSTRAINT ck_ocorrencia_lat CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ocorrencia_lon CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);
CREATE UNIQUE INDEX ux_ocorrencia_externa ON ocorrencia (fonte_id, identificador_externo) WHERE identificador_externo IS NOT NULL;
CREATE INDEX ix_ocorrencia_coordenadas ON ocorrencia (latitude, longitude) WHERE latitude IS NOT NULL;
CREATE INDEX ix_ocorrencia_municipio ON ocorrencia (codigo_ibge, data_ocorrencia);
CREATE INDEX ix_ocorrencia_status ON ocorrencia (status_validacao, data_registro);
